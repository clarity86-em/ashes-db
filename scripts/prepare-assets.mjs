import {cp,mkdir,readFile,writeFile,rm} from 'node:fs/promises';
await mkdir('public',{recursive:true});
for(const name of ['src','data','LICENSE','THIRD_PARTY.md']){
  await rm(`public/${name}`,{recursive:true,force:true});await cp(name,`public/${name}`,{recursive:true});
}
const html=await readFile('index.html','utf8');
const body=html.match(/<body>([\s\S]*?)<\/body>/)[1].replace(/<script[^>]*>[\s\S]*?<\/script>/g,'');
await writeFile('app/shell.ts',`// Generated by prepare-assets.mjs from index.html.\nexport default ${JSON.stringify(body)};\n`);
